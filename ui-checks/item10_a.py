import re
from playwright.sync_api import sync_playwright
from common import *
with sync_playwright() as p:
    b, page = open_page(p)
    page.goto(BASE + "/databaseServices/add-service")
    page.get_by_placeholder("Search for a connector").fill("Oracle")
    page.get_by_test_id("Oracle").click()
    page.get_by_placeholder("Service Name").fill("dqlab_oracle")
    page.locator("input[id='root/username']").fill(env("SOURCE_ORACLE_USER"))
    page.get_by_test_id("oneof-option-1").click()
    page.locator("input[id='root/oracleConnectionType/oracleServiceName']").fill("XEPDB1")
    page.locator("input[id='root/hostPort']").fill("source-oracle:1521")
    pw = page.locator("input[id='root/password']")
    if not pw.is_visible():
        page.get_by_text("Authentication", exact=True).click()
    pw.fill(env("SOURCE_ORACLE_PASSWORD"))
    shot(page, "i10_5_filled")
    page.get_by_test_id("test-connection-btn").click()
    page.wait_for_timeout(15000)
    shot(page, "i10_6_tested")
    page.get_by_role("button", name="Done").click()
    page.get_by_test_id("next-button").click()
    page.wait_for_load_state("networkidle")
    page.get_by_test_id("schemaFilterPattern-only-specific-button").click()
    page.wait_for_timeout(800)
    page.get_by_role("button", name="contains").first.click()
    page.get_by_role("option", name="matches regex").click()
    lab = page.get_by_text("Include only schemas where the name", exact=False)
    lab.locator("xpath=following::input[1]").fill("(?i)^dqlab$")
    lab.locator("xpath=following::button[.//text()[contains(.,'Add')] or normalize-space()='Add'][1]").click()
    page.wait_for_timeout(800)
    lab.scroll_into_view_if_needed()
    shot(page, "i10_7_ingest")
    page.get_by_test_id("next-button").click()
    page.wait_for_timeout(8000)
    shot(page, "i10_8_deployed")
    print(page.url)
