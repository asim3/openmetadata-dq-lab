from playwright.sync_api import sync_playwright
from common import *
with sync_playwright() as p:
    b, page = open_page(p)
    page.goto(BASE + "/databaseServices/add-service")
    page.get_by_placeholder("Search for a connector").fill("MySQL")
    page.get_by_test_id("Mysql").click() if page.get_by_test_id("Mysql").count() else page.get_by_test_id("MySQL").click()
    page.get_by_placeholder("Service Name").fill("dqlab_mysql")
    page.wait_for_timeout(800)
    page.locator("input[id='root/username']").fill(env("SOURCE_MYSQL_USER"))
    page.locator("input[id='root/hostPort']").fill("source-mysql:3306")
    page.locator("input[id='root/authType/password']").fill(env("SOURCE_MYSQL_PASSWORD"))
    page.get_by_text("Scope & Options", exact=True).click(); page.wait_for_timeout(600)
    print([e.id for e in page.query_selector_all("input") if e.is_visible() and e.get_attribute("id","").startswith("root/")] if False else page.evaluate("[...document.querySelectorAll('input')].filter(e=>e.offsetParent&&e.id.startsWith('root/')).map(e=>e.id+'|'+e.type)"))
    page.locator("input[id='root/databaseSchema']").fill("dqlab")
    shot(page, "i02_2_filled")
    page.get_by_test_id("test-connection-btn").click(); page.wait_for_timeout(15000)
    shot(page, "i02_3_tested")
    page.get_by_role("button", name="Done").click(); page.wait_for_timeout(500)
    print("banner:", " ".join(page.get_by_test_id("next-button").locator("xpath=ancestor::form[1] | ancestor::div[1]").first.inner_text().split())[-200:])
    page.get_by_test_id("next-button").click(); page.wait_for_timeout(3000)
    shot(page, "i02_4_ingest")
    t = " ".join(page.locator("body").inner_text().split())
    print(t[t.find("What should we ingest"):][:900])
    print("exclude chips:", page.evaluate("[...document.querySelectorAll('*')].filter(e=>e.children.length==0 && /^is exactly|^starts with|^matches/.test(e.innerText||'')).map(e=>e.innerText)"))
    page.get_by_test_id("next-button").click(); page.wait_for_timeout(8000)
    print(page.url); shot(page, "i02_5_deployed")
    b.close()
